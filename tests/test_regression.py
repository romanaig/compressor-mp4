class Api(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        s, cls.land = upload(VIDEOS / "landscape.mp4")
        assert s == 200, cls.land

    def test_config(self):
        s, c = http("GET", "/api/config")
        self.assertEqual(s, 200)
        self.assertEqual(c["version"], sv.VERSION)
        self.assertIn(".mov", c["extensions"])
        self.assertEqual(c["caps"], [1080, 720, 480, 360, 240, 144])
        self.assertEqual(set(c["formats"]), {"mp4", "mov", "webm"})

    def test_upload_info(self):
        v = self.land
        self.assertEqual((v["width"], v["height"]), (1280, 720))
        self.assertAlmostEqual(v["duration"], 6.0, delta=0.1)
        self.assertEqual(v["fps"], 25.0)
        self.assertTrue(v["audio"])
        self.assertEqual((v["codec"], v["chroma"]), ("h264", "4:2:0"))
        self.assertEqual(len(v["samples"]), 6)
        self.assertEqual(v["sample_seconds"], 2.0)

    def test_upload_non_ascii_name_and_mov(self):
        s, v = upload(VIDEOS / "portrait çã.mov")
        self.assertEqual(s, 200, v)
        self.assertEqual(v["name"], "portrait çã.mov")
        self.assertFalse(v["audio"])
        self.assertEqual((v["width"], v["height"]), (720, 1280))

    def test_upload_same_file_is_reused(self):
        s, v = upload(VIDEOS / "landscape.mp4")
        self.assertEqual((s, v["name"]), (200, "landscape.mp4"))
        self.assertEqual(len(list(FOLDERS.input.glob("landscape*.mp4"))), 1)

    def test_upload_same_name_other_file_gets_suffix(self):
        s, v = upload(VIDEOS / "odd.mkv", name="landscape.mp4")
        self.assertEqual(s, 200, v)
        self.assertRegex(v["name"], r"^landscape_\d+\.mp4$")

    def test_upload_malicious_path_stays_in_input(self):
        s, v = upload(VIDEOS / "odd.mkv", name="../../outside.mkv")
        self.assertEqual(s, 200, v)
        self.assertEqual(v["name"], "outside.mkv")
        self.assertTrue((FOLDERS.input / "outside.mkv").exists())
        self.assertFalse((TMP / "outside.mkv").exists())

    def test_upload_wrong_format(self):
        s, r = upload(VIDEOS / "text.txt")
        self.assertEqual(s, 400)
        self.assertIn("format", r["error"])

    def test_upload_broken_file(self):
        s, r = upload(VIDEOS / "broken.mp4")
        self.assertEqual(s, 400, r)

    def test_info_missing_and_traversal(self):
        for name in ("missing.mp4", "../app/server.py", "..", ""):
            s, _ = http("GET", "/api/info?v=" + urllib.parse.quote(name))
            self.assertEqual(s, 404, name)

    def test_frame_png_and_limits(self):
        for t in ("0", "3", "5.99", "999", "-4", "nan", "abc"):
            s, png = http("GET", f"/api/frame?v=landscape.mp4&t={t}", json_=False)
            if t == "abc":
                self.assertEqual(s, 400)
                continue
            self.assertEqual(s, 200, t)
            self.assertTrue(png.startswith(b"\x89PNG"), t)

    def test_repeated_frame_comes_from_cache(self):
        http("GET", "/api/frame?v=landscape.mp4&t=4.2", json_=False)
        t0 = time.time()
        s, _ = http("GET", "/api/frame?v=landscape.mp4&t=4.2", json_=False)
        self.assertEqual(s, 200)
        self.assertLess(time.time() - t0, 0.05, "the second time must come from the cache")

    def test_params(self):
        s, p = http("GET", "/api/params?v=landscape.mp4&pct=72.5")
        self.assertEqual(s, 200)
        self.assertEqual((p["crf"], p["height"], p["width"], p["pct"], p["codec"]), (33.95, 720, 1280, 72.5, "H.264 / AAC"))
        s, p = http("GET", "/api/params?v=landscape.mp4&pct=85")
        self.assertEqual((p["height"], p["width"]), (540, 960))
        s, p = http("GET", "/api/params?v=landscape.mp4&pct=10&cap=360&fps=12&format=webm")
        self.assertEqual((p["width"], p["height"], p["fps"], p["format"], p["extension"]), (640, 360, 12.0, "webm", ".webm"))
        self.assertEqual(http("GET", "/api/params?v=landscape.mp4&cap=999")[0], 400)

    def test_estimate(self):
        estimates = []
        for pct in (0, 50, 90):
            s, r = http("POST", "/api/estimate", {"v": "landscape.mp4", "pct": pct})
            self.assertEqual(s, 200, r)
            self.assertEqual(r["samples"], 6)
            self.assertEqual(r["reduction_pct"], round(r["reduction_pct"], 2))
            estimates.append(r["estimate_bytes"])
        self.assertGreater(estimates[0], estimates[1])
        self.assertGreater(estimates[1], estimates[2])
        t0 = time.time()
        s, r2 = http("POST", "/api/estimate", {"v": "landscape.mp4", "pct": 90})
        self.assertLess(time.time() - t0, 0.5, "the second time must come from the cache")
        self.assertEqual(r2["estimate_bytes"], estimates[2])
        self.assertEqual(http("POST", "/api/estimate", {"v": "missing.mp4", "pct": 1})[0], 404)

    def test_estimate_fewer_fps_smaller_file(self):
        _, full = http("POST", "/api/estimate", {"v": "landscape.mp4", "pct": 30})
        _, low = http("POST", "/api/estimate", {"v": "landscape.mp4", "pct": 30, "fps": 5})
        self.assertLess(low["estimate_bytes"], full["estimate_bytes"])

    def test_estimate_close_to_real(self):
        for fmt in ("mp4", "webm"):
            _, e = http("POST", "/api/estimate", {"v": "landscape.mp4", "pct": 40, "format": fmt})
            _, r = http("POST", "/api/render", {"v": "landscape.mp4", "pct": 40, "format": fmt})
            real = wait_render(r["job"])["bytes"]
            self.assertLess(abs(e["estimate_bytes"] / real - 1), 0.35, (fmt, e["estimate_bytes"], real))

    def test_estimate_short_video(self):
        upload(VIDEOS / "odd.mkv")
        s, r = http("POST", "/api/estimate", {"v": "odd.mkv", "pct": 50})
        self.assertEqual(s, 200, r)
