class Rules(unittest.TestCase):
    def test_clamp_pct(self):
        cases = {-5: 0.0, 0: 0.0, 150: 100.0, "33.333": 33.33, "abc": 0.0, None: 0.0,
                 float("nan"): 0.0, float("inf"): 100.0, 72.5: 72.5, "99.999": 100.0}
        for value, expected in cases.items():
            self.assertEqual(cz.clamp_pct(value), expected, value)

    def test_crf_goes_from_18_to_40_and_only_rises(self):
        self.assertEqual(cz.params(0, 1920, 1080).crf, 18.0)
        self.assertEqual(cz.params(100, 1920, 1080).crf, 40.0)
        crfs = [cz.params(p / 4, 1920, 1080).crf for p in range(401)]
        self.assertEqual(crfs, sorted(crfs))

    def test_vp9_crf_integer_from_24_to_54(self):
        vp9 = [cz.params(p, 1920, 1080, format="webm").crf for p in range(101)]
        self.assertEqual((vp9[0], vp9[-1]), (24.0, 54.0))
        self.assertTrue(all(c == int(c) for c in vp9))
        self.assertEqual(vp9, sorted(vp9))

    def test_resolution_steps(self):
        p59 = cz.params(59.99, 1920, 1080)
        self.assertEqual((p59.width, p59.height), (1920, 1080))
        p60 = cz.params(60, 1920, 1080)
        self.assertEqual((p60.width, p60.height), (1280, 720))
        p80 = cz.params(80, 1920, 1080)
        self.assertEqual((p80.width, p80.height), (960, 540))

    def test_cap_limits_beyond_the_slider(self):
        p = cz.params(10, 1920, 1080, cap=480)
        self.assertEqual((p.width, p.height), (854, 480))
        p = cz.params(85, 1920, 1080, cap=720)               # slider asks for 540: the smaller wins
        self.assertEqual((p.width, p.height), (960, 540))
        p = cz.params(10, 1280, 720, cap=1080)               # cap above the original: no upscaling
        self.assertEqual((p.width, p.height), (1280, 720))
        p = cz.params(10, 1080, 1920, cap=144)               # portrait: shorter side
        self.assertEqual((p.width, p.height), (144, 256))

    def test_portrait_uses_shorter_side(self):
        p = cz.params(60, 1080, 1920)
        self.assertEqual((p.width, p.height), (720, 1280))

    def test_never_upscales(self):
        p = cz.params(100, 854, 480)
        self.assertEqual((p.width, p.height), (854, 480))

    def test_dimensions_always_even(self):
        for pct in (0, 30, 60, 80, 100):
            for cap in (None, 360, 144):
                for w, h in ((641, 361), (1919, 1079), (1081, 1921), (3, 3)):
                    p = cz.params(pct, w, h, cap=cap)
                    self.assertEqual(p.width % 2, 0, (pct, w, h, cap))
                    self.assertEqual(p.height % 2, 0, (pct, w, h, cap))
                    self.assertGreaterEqual(min(p.width, p.height), 2)

    def test_audio(self):
        self.assertEqual([cz.params(x, 1920, 1080).audio_kbps for x in (0, 49.99, 50, 79.99, 80, 100)],
                         [160, 160, 128, 128, 96, 96])
        self.assertEqual([cz.params(x, 1920, 1080, format="webm").audio_kbps for x in (0, 50, 80)], [128, 96, 64])

    def test_fps_never_rises(self):
        self.assertIsNone(cz.params(50, 1920, 1080, fps=30, source_fps=25).fps)
        self.assertIsNone(cz.params(50, 1920, 1080, fps=25, source_fps=25).fps)
        self.assertIsNone(cz.params(50, 1920, 1080, fps=23.98, source_fps=23.976).fps)   # "same" as the original
        self.assertEqual(cz.params(50, 1920, 1080, fps=12, source_fps=25).fps, 12)

    def test_settings_from_request(self):
        s = cz.Settings.from_request({"pct": "72.5", "cap": "480", "fps": "12", "format": ".WEBM"})
        self.assertEqual(s, cz.Settings(72.5, 480, 12.0, "webm"))
        self.assertEqual(cz.Settings.from_request({}), cz.Settings(0.0, None, None, "mp4"))
        self.assertEqual(cz.Settings.from_request({"fps": "0.2"}).fps, 1.0)            # minimum 1 fps
        for bad in ({"cap": 999}, {"cap": "x"}, {"fps": "-3"}, {"fps": "nan"}, {"format": "avi"}):
            with self.assertRaises(ValueError, msg=bad):
                cz.Settings.from_request(bad)

    def test_timecode(self):
        cases = {0: "00:00", 0.99: "00:00", 59.9: "00:59", 61: "01:01", 600: "10:00",
                 3599.9: "59:59", 3600: "1:00:00", 3725: "1:02:05", -3: "00:00"}
        for s, expected in cases.items():
            self.assertEqual(cz.timecode(s), expected, s)

    def test_timecode_with_frame(self):
        cases = {(3.04, 25): "00:03:01", (0, 25): "00:00:00", (6.0, 25): "00:06:00",
                 (2.0, 23.976): "00:01:23",          # t = 2.0 s is still frame 47 (starts at 1.960 s)
                 (2.0021, 23.976): "00:02:00", (3725.5, 30): "1:02:05:15", (1 / 30 * 29, 30): "00:00:29"}
        for (s, fps), expected in cases.items():
            self.assertEqual(cz.timecode(s, fps), expected, (s, fps))
        self.assertEqual(cz.frame_number(3.04, 25), 76)

    def test_reduction(self):
        self.assertEqual(cz.reduction_pct(1000, 250), 75.0)
        self.assertEqual(cz.reduction_pct(1000, 1500), -50.0)
        self.assertEqual(cz.reduction_pct(0, 10), 0.0)
        self.assertEqual(cz.reduction_pct(3, 1), 66.67)

    def test_ffmpeg_args(self):
        a = cz.encoding_args(cz.params(72.5, 1920, 1080))
        self.assertIn("libx264", a)
        self.assertEqual(a[a.index("-preset") + 1], "faster")   # picked after the benchmark
        self.assertIn("33.95", a)                      # CRF with 2 decimals
        self.assertIn("scale=1280:720:flags=lanczos,format=yuv420p", a)
        w = cz.encoding_args(cz.params(50, 1920, 1080, fps=12, source_fps=25, format="webm"))
        self.assertEqual(w[1], "fps=12,scale=1920:1080:flags=lanczos,format=yuv420p")   # fps before scaling
        for item in ("libvpx-vp9", "libopus", "39"):
            self.assertIn(item, w)
        self.assertNotIn("+faststart", w)

    def test_output_name(self):
        self.assertEqual(cz.output_name("clip", cz.params(70, 1920, 1080)), "clip_c70.00.mp4")
        self.assertEqual(cz.output_name("clip", cz.params(70, 1920, 1080, fps=12, source_fps=25, format="webm")),
                         "clip_c70.00_12fps.webm")

    def test_samples(self):
        self.assertEqual(cz.sample_starts(2.0), (2.0, [0.0]))
        length, starts = cz.sample_starts(62.0)
        self.assertEqual((length, len(starts)), (2.0, 6))
        self.assertTrue(all(0 <= s <= 60 for s in starts))

    def test_parse_ffmpeg_info(self):
        text = ("  Duration: 00:00:57.06, start: 0.000000, bitrate: 15497 kb/s\n"
                "  Stream #0:0[0x1](und): Video: prores (HQ) (apch / 0x68637061), yuv422p10le(tv, bt709, progressive), "
                "1920x1080, 182000 kb/s, 25 fps, 25 tbr, 12800 tbn (default)\n"
                "  Stream #0:1[0x2](und): Audio: pcm_s16le (sowt / 0x74776F73), 48000 Hz, stereo\n")
        i = fe.parse_info(text)
        self.assertEqual((i["codec"], i["profile"], i["chroma"], i["bits"], i["color_space"], i["color_range"]),
                         ("prores", "HQ", "4:2:2", 10, "bt709", "tv"))
        self.assertEqual((i["width"], i["height"], i["fps"], i["duration"], i["audio"]), (1920, 1080, 25.0, 57.06, True))
        phone = ("Duration: 00:00:03.00\n Stream #0:0: Video: h264 (avc1 / 0x31637661), yuv420p, 1920x1080, 30 fps\n"
                 "    Side data:\n      displaymatrix: rotation of -90.00 degrees\n")
        i = fe.parse_info(phone)
        self.assertEqual((i["width"], i["height"], i["profile"], i["color_space"]), (1080, 1920, None, None))
        with self.assertRaises(ValueError):
            fe.parse_info("Input #0, png_pipe\n")

    def test_lru_cache(self):
        c, computed = LRUCache(2), []
        calc = lambda k: (lambda: computed.append(k) or k * 10)   # noqa: E731
        self.assertEqual([c.get(1, calc(1)), c.get(2, calc(2)), c.get(1, calc(1))], [10, 20, 10])
        c.get(3, calc(3))                                          # 2 is the oldest: evicted
        c.get(2, calc(2))
        self.assertEqual(computed, [1, 2, 3, 2])
        self.assertEqual(len(c), 2)

    def test_file_names(self):
        self.assertEqual(safe_name("..\\..\\a:b?.MOV"), "a_b_.mov")
        with self.assertRaises(ValueError):
            safe_name("notes.txt")
        (TMP / "free.mp4").write_bytes(b"x")
        self.assertEqual(free_name(TMP / "free.mp4").name, "free_2.mp4")
        self.assertEqual(free_name(TMP / "free.mp4", {"free_2.mp4"}).name, "free_3.mp4")


