    def test_preview_errors(self):
        self.assertEqual(http("POST", "/api/preview", {"v": "missing.mp4", "t": 0, "pct": 1})[0], 404)
        self.assertEqual(http("POST", "/api/preview", b"{not json", {"Content-Type": "application/json"})[0], 400)
        self.assertEqual(http("POST", "/api/preview", {"v": "landscape.mp4", "t": "x", "pct": 1})[0], 400)
        self.assertEqual(http("POST", "/api/preview", {"v": "landscape.mp4", "t": 1, "format": "gif"})[0], 400)

    def test_render(self):
        s, r = http("POST", "/api/render", {"v": "landscape.mp4", "pct": 72.5})
        self.assertEqual(s, 200, r)
        j = wait_render(r["job"])
        self.assertEqual(j["state"], "done", j)
        self.assertEqual(j["progress"], 100.0)
        self.assertRegex(j["output"], r"^landscape_c72\.50(_\d+)?\.mp4$")
        out = FOLDERS.output / j["output"]
        inf = FF.info(out)
        self.assertEqual((inf["width"], inf["height"]), (1280, 720))
        self.assertAlmostEqual(inf["duration"], 6.0, delta=0.2)
        self.assertTrue(inf["audio"])
        self.assertEqual(j["bytes"], out.stat().st_size)
        self.assertFalse(list(FOLDERS.output.glob("*.partial*")))

    def test_render_mov_and_webm_with_fps_and_cap(self):
        for fmt, codec in (("mov", "h264"), ("webm", "vp9")):
            _, r = http("POST", "/api/render", {"v": "landscape.mp4", "pct": 30, "format": fmt, "fps": 12.5, "cap": 360})
            j = wait_render(r["job"])
            self.assertEqual(j["state"], "done", j)
            self.assertRegex(j["output"], rf"^landscape_c30\.00_12\.5fps(_\d+)?\.{fmt}$")
            inf = FF.info(FOLDERS.output / j["output"])
            self.assertEqual((inf["codec"], inf["width"], inf["height"], inf["fps"]), (codec, 640, 360, 12.5))
            self.assertAlmostEqual(inf["duration"], 6.0, delta=0.25)
            self.assertTrue(inf["audio"])

