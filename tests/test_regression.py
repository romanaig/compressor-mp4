def open_browser(pw):
    """Playwright's Chromium if installed; otherwise the system Edge or Chrome."""
    for attempt in ({}, {"channel": "msedge"}, {"channel": "chrome"}):
        try:
            return pw.chromium.launch(**attempt)
        except Exception:
            continue
    return None


class Interface(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        try:
            from playwright.sync_api import sync_playwright
        except ImportError:
            raise unittest.SkipTest("Playwright not installed (pip install playwright)")
        cls.pw = sync_playwright().start()
        cls.browser = open_browser(cls.pw)
        if not cls.browser:
            cls.pw.stop()
            raise unittest.SkipTest("no browser available for Playwright")
        cls.page = cls.browser.new_page(viewport={"width": 1400, "height": 860})
        cls.console_errors = []
        cls.page.on("console", lambda m: m.type == "error" and cls.console_errors.append(m.text))
        cls.page.on("pageerror", lambda e: cls.console_errors.append(str(e)))
        cls.page.goto(BASE + "/")
        cls.page.wait_for_function("document.querySelector('#formats').children.length === 3")

    @classmethod
    def tearDownClass(cls):
        cls.browser.close()
        cls.pw.stop()

    def drop(self, path: Path, name=None):
        b64 = base64.b64encode(path.read_bytes()).decode()
        dt_ = self.page.evaluate_handle(
            """([b64, name]) => { const bin = atob(b64); const u = new Uint8Array(bin.length);
                for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
                const d = new DataTransfer(); d.items.add(new File([u], name, {type: 'video/mp4'})); return d; }""",
            [b64, name or path.name])
        self.page.dispatch_event("body", "dragenter", {"dataTransfer": dt_})
        self.assertIn("dragging", self.page.get_attribute("body", "class") or "")
        self.page.dispatch_event("body", "drop", {"dataTransfer": dt_})

    def move_time(self, t, release=True):
        end = "e.dispatchEvent(new Event('change'));" if release else ""
        self.page.eval_on_selector("#timeline", f"e => {{ e.value = {t}; e.dispatchEvent(new Event('input')); {end} }}")

    def set_pct(self, value):
        self.page.fill("#pctNum", str(value))
        self.page.eval_on_selector("#pctNum", "e => e.blur()")

    def chip(self, box, text):
        self.page.click(f"{box} .chip:text-is('{text}')")

    def wait_preview(self):
        self.page.wait_for_function("document.querySelector('#msg').textContent === 'Preview ready.'", timeout=120000)

    def test_1_full_flow(self):
        p = self.page
        self.assertTrue(p.is_disabled("#btPreview"))
        self.assertEqual(p.text_content("#timecode"), "00:00:00 / 00:00:00")
        self.drop(VIDEOS / "landscape.mp4")
        p.wait_for_function("document.querySelector('#fileInfo').textContent.startsWith('landscape.mp4')")
        self.assertNotIn("dragging", p.get_attribute("body", "class") or "")
        self.assertFalse(p.is_disabled("#btPreview"))
        self.assertEqual(p.text_content("#timecode"), "00:00:00 / 00:06:00")
        self.assertEqual(p.eval_on_selector_all("#sampleMarks i", "l => l.length"), 6)
        self.assertTrue(p.text_content("#colorInfo").startswith("Color space:"))
        self.assertTrue(p.text_content("#rawCaption").startswith("Original · H.264"))
        p.wait_for_function("document.querySelector('#rawImg').naturalWidth === 1280")

        # timeline → timecode (minute:second:frame), frame number and raw frame
        self.move_time(3.04)
        self.assertEqual(p.text_content("#timecode"), "00:03:01 / 00:06:00")
        self.assertEqual(p.text_content("#frameInfo"), "FRAME 76 · 25.00 FPS")
        p.wait_for_function("document.querySelector('#rawImg').src.includes('t=3.040')")
        p.wait_for_function("document.querySelector('#rawTime').textContent === '00:03:01'")

        # ⏩ and ⏪: one frame
        p.click("#btForward")
        self.assertEqual(p.text_content("#frameInfo"), "FRAME 77 · 25.00 FPS")
        p.click("#btBack")
        self.assertEqual(p.text_content("#frameInfo"), "FRAME 76 · 25.00 FPS")

        # % with two decimals: number → slider
        self.set_pct(72.5)
        self.assertEqual(p.input_value("#pctNum"), "72.50")
        self.assertEqual(float(p.input_value("#pct")), 72.5)
        p.wait_for_function("document.querySelector('#params').textContent.includes('33.95')")
        self.assertIn("1280×720", p.text_content("#params"))

        # slider → number
        p.eval_on_selector("#pct", "e => { e.value = 33.333; e.dispatchEvent(new Event('input')); }")
        self.assertEqual(p.input_value("#pctNum"), "33.33")
        self.set_pct(72.5)

        # preview
        p.click("#btPreview")
        self.wait_preview()
        self.assertTrue(p.get_attribute("#compImg", "src").startswith("data:image/png"))
        self.assertEqual(p.text_content("#compTime"), "00:03:01 · 72.50 %")
        self.assertEqual(p.text_content("#compRes"), " · 1280×720")
        p.wait_for_function("document.querySelector('#estSize').textContent.includes('≈')", timeout=120000)
        self.assertRegex(p.text_content("#estOriginal"), r"^\d+\.\d{2} MB$")
        self.assertRegex(p.text_content("#estSize"), r"^≈ \d+\.\d{2} MB$")
        self.assertRegex(p.text_content("#estReduction"), r"^[−+]\d+\.\d{2} % at 72\.50 %$")
        self.assertNotIn("stale", p.get_attribute("#compScreen", "class"))

        # synced 1:1 zoom on both screens
        p.click("#rawImg")
        self.assertIn("zoom", p.get_attribute(".screens", "class"))
        self.assertTrue(p.is_visible("#compScreen .zoom-badge"))
        self.assertEqual(p.eval_on_selector("#compImg", "e => e.getBoundingClientRect().width"), 1280)
        # layout must not overflow: screens side by side, same size, timeline inside the window
        width, height = p.evaluate("innerWidth"), p.evaluate("innerHeight")
        raw = p.eval_on_selector("#rawScreen", "e => e.getBoundingClientRect().toJSON()")
        comp = p.eval_on_selector("#compScreen", "e => e.getBoundingClientRect().toJSON()")
        self.assertLessEqual(comp["right"], width)
        self.assertLess(raw["right"], comp["left"])
        self.assertAlmostEqual(raw["width"], comp["width"], delta=2)
        self.assertLessEqual(p.eval_on_selector("#timecode", "e => e.getBoundingClientRect().bottom"), height)
        self.assertTrue(p.is_visible("#timecode"))
        p.eval_on_selector("#rawScreen .img", "e => { e.scrollLeft = 200; e.scrollTop = 100; }")
        p.wait_for_timeout(100)
        self.assertEqual(p.eval_on_selector("#compScreen .img", "e => [e.scrollLeft, e.scrollTop]"),
                         p.eval_on_selector("#rawScreen .img", "e => [e.scrollLeft, e.scrollTop]"))
        p.click("#compImg")
        self.assertNotIn("zoom", p.get_attribute(".screens", "class"))

        # frame or setting changed → preview goes stale; changed back → fresh again
        self.move_time(1, release=False)
        self.assertIn("stale", p.get_attribute("#compScreen", "class"))
        self.move_time(3.04, release=False)
        self.assertNotIn("stale", p.get_attribute("#compScreen", "class"))
        self.chip("#fpsPresets", "12 fps")
        self.assertIn("stale", p.get_attribute("#compScreen", "class"))
        self.chip("#fpsPresets", "Orig (25)")
        self.assertNotIn("stale", p.get_attribute("#compScreen", "class"))

        # 72.125: Python and JS round differently; must not mark stale for nothing
        self.set_pct(72.125)
        p.keyboard.press("p")                                     # Preview shortcut
        self.wait_preview()
        self.assertNotIn("stale", p.get_attribute("#compScreen", "class"))

        # render (R shortcut)
        self.set_pct(72.5)
        p.keyboard.press("r")
        p.wait_for_function("document.querySelector('#btPreview').disabled")
        p.wait_for_function("document.querySelector('#msg').textContent.startsWith('Done')", timeout=180000)
        self.assertRegex(p.text_content("#msg"), r"output/landscape_c72\.50(_\d+)?\.mp4 · \d+\.\d{2} MB · [−+]\d+\.\d{2} %")
        self.assertTrue(p.is_visible("#btOutput"))
        self.assertFalse(p.is_disabled("#btRender"))

